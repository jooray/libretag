#!/usr/bin/env bash
# LibreTag on ZephCore: the clone in firmware/zephcore is upstream at the commit in
# firmware/zephcore.lock plus our commits on branch `libretag`, exported as a patch series in
# firmware/zephcore-patches/.
#
#   zephcore.sh setup          clone at the locked commit, apply the series, west update
#   zephcore.sh export         commits on `libretag` -> firmware/zephcore-patches/ (+ version header)
#   zephcore.sh update <ref>   rebase `libretag` onto a newer upstream ref; resolve, then export
#   zephcore.sh status         base, our commits, uncommitted changes, upstream ahead
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
FW=$ROOT/firmware
WS=$FW/zephcore
PATCHES=$FW/zephcore-patches
LOCK=$FW/zephcore.lock
url=$(sed -n 's/^url=//p' "$LOCK")
base=$(sed -n 's/^commit=//p' "$LOCK")

die() { echo "zephcore.sh: $*" >&2; exit 1; }

write_version() {
	# compiled into the tracker: `version` and `status` print it
	local v
	v=$(tr -d ' \n' < "$FW/VERSION")
	cat > "$WS/zephcore/src/lt_version.h" <<H
/* Generated by firmware/tools/zephcore.sh; do not edit. */
#pragma once
#define LT_FW_VERSION "$v"
#define LT_ZEPHCORE_BASE "${base:0:12}"
H
}

PATCH_NAME=${LT_PATCH_NAME:-LibreTag}
PATCH_EMAIL=${LT_PATCH_EMAIL:-dev@libretag.invalid}

case "${1:-}" in
setup)
	[ -e "$WS/.git" ] && die "$WS exists; remove it first or use status/export"
	git clone "$url" "$WS"
	git -C "$WS" checkout -q -b libretag "$base"
	git -C "$WS" config user.name "$PATCH_NAME"
	git -C "$WS" config user.email "$PATCH_EMAIL"
	git -C "$WS" am -q --3way "$PATCHES"/*.patch
	(cd "$WS" && west init -l zephcore >/dev/null 2>&1 || true; west update)
	echo "ready: $WS on libretag ($(git -C "$WS" rev-list --count "$base"..libretag) commits on $base)"
	;;
export)
	git -C "$WS" rev-parse -q --verify libretag >/dev/null || die "no branch libretag in $WS"
	write_version
	if [ -n "$(git -C "$WS" status --porcelain)" ]; then
		die "uncommitted changes in $WS; commit them on libretag first (git -C $WS commit -am ...)"
	fi
	rm -rf "$PATCHES"
	git -C "$WS" format-patch -q --no-signature --zero-commit -o "$PATCHES" "$base"..libretag
	# the published patches carry the project identity, never a personal address
	for p in "$PATCHES"/*.patch; do
		sed -i.bak "2s/^From: .*/From: $PATCH_NAME <$PATCH_EMAIL>/" "$p" && rm -f "$p.bak"
	done
	echo "exported $(ls "$PATCHES" | wc -l | tr -d ' ') patch(es) to $PATCHES"
	;;
update)
	ref=${2:?usage: zephcore.sh update <upstream ref>}
	git -C "$WS" fetch -q origin
	new=$(git -C "$WS" rev-parse "origin/$ref" 2>/dev/null || git -C "$WS" rev-parse "$ref")
	echo "rebasing libretag: ${base:0:12} -> ${new:0:12}"
	echo "upstream changes in files we touch:"
	git -C "$WS" diff --stat "$base" "$new" -- $(git -C "$WS" diff --name-only "$base" libretag) || true
	git -C "$WS" checkout -q libretag
	if git -C "$WS" rebase --onto "$new" "$base" libretag; then
		sed -i '' "s/^commit=.*/commit=$new/; s/^date=.*/date=$(git -C "$WS" log -1 --format=%cs "$new")/" "$LOCK"
		base=$new
		(cd "$WS" && west update)
		echo "rebased; build and test on hardware, then: zephcore.sh export"
	else
		echo "conflicts: resolve in $WS, git rebase --continue, then edit commit= in $LOCK to $new and export"
		exit 1
	fi
	;;
status)
	echo "upstream: $url"
	echo "base:     $base ($(sed -n 's/^date=//p' "$LOCK"))"
	echo "ours:     $(git -C "$WS" rev-list --count "$base"..libretag 2>/dev/null || echo '?') commit(s) on libretag"
	git -C "$WS" status --short | sed 's/^/  dirty: /'
	git -C "$WS" fetch -q origin 2>/dev/null && \
		echo "upstream master is $(git -C "$WS" rev-list --count "$base"..origin/master 2>/dev/null || echo '?') commit(s) ahead of base"
	;;
*)
	sed -n '2,12p' "$0"; exit 1
	;;
esac
