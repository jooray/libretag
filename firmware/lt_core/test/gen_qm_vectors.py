"""quiet-mesh-v1.json (a copy of docs/vectors/quiet-mesh-v1.json, kept identical by tools/check_vectors.py)
-> qm_vectors.h (stdlib only): python3 gen_qm_vectors.py"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
v = json.loads((here / "quiet-mesh-v1.json").read_text())


def arr(h, n=None):
    b = bytes.fromhex(h) if isinstance(h, str) else bytes(h)
    if n is not None:
        b = b + bytes(n - len(b))
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}" if b else "{0}"


def cs(s):
    return "NULL" if s is None else f'"{s}"'


o = ["/* Generated by gen_qm_vectors.py from quiet-mesh-v1.json. Do not edit. */", "#pragma once",
     "#include <stddef.h>", "#include <stdint.h>"]
o.append(f"static const uint8_t QV_VIEW4[] = {arr(v['view4'])};")
o.append(f"static const uint8_t QV_CMD4[] = {arr(v['cmd4'])};")
o.append(f"static const uint8_t QV_K0[] = {arr(v['k0'])};")
# copies
o.append("struct qcopy { uint32_t n; uint8_t pt[33]; uint8_t pk[32]; uint8_t tags[5][4]; uint8_t j; const char *scope;"
         " uint8_t path_n; uint8_t path[4]; uint8_t p[45]; uint8_t packet[64]; uint8_t plen; uint8_t header; };")
o.append("static const struct qcopy QV_COPIES[] = {")
for c in v["copies"]:
    tags = "{" + ", ".join(arr(c["tags"][str(j)]) for j in (0, 1, 9, 10, 11)) + "}"
    for x in c["copies"]:
        path = "".join(x["path"])
        pk = bytes.fromhex(x["packet"])
        o.append(f"\t{{{c['n']}, {arr(c['pt'])}, {arr(c['pk'])}, {tags}, {x['j']}, {cs(x['scope'])}, {len(x['path'])}, "
                 f"{arr(path, 4)}, {arr(x['p'])}, {arr(pk.hex(), 64)}, {len(pk)}, {x['header']}}},")
o.append("};")
# acks
o.append("struct qack { uint32_t n; uint16_t k; uint8_t hold, more, routed; uint8_t tag[4]; uint8_t pa[13];"
         " uint8_t chan[19]; uint8_t packet[21]; uint8_t stealth[19]; };")
o.append("static const struct qack QV_ACKS[] = {")
for a in v["acks"]["valid"]:
    o.append(f"\t{{{a['n']}, {a['k']}, {a['hold']}, {int(a['more'])}, {int(a['routed'])}, {arr(a['tag'])}, {arr(a['pa'])}, "
             f"{arr(a['channel_payload'])}, {arr(a['packet'])}, {arr(a['stealth'])}}},")
o.append("};")
o.append("struct qbad { uint32_t n; uint16_t k; uint8_t len; uint8_t dg[24]; const char *why; };")
o.append("static const struct qbad QV_ACKS_BAD[] = {")
for a in v["acks"]["invalid"] + v["acks_routed"]["invalid"]:
    d = bytes.fromhex(a["datagram"])
    o.append(f"\t{{{a['n']}, {a['k']}, {len(d)}, {arr(d.hex(), 24)}, \"{a['why']}\"}},")
o.append("};")
o.append("struct qrack { uint32_t n; uint16_t k; uint8_t hs; uint8_t count; uint8_t path[6]; uint8_t pa[13]; uint8_t dlen;"
         " uint8_t dg[20]; uint8_t clen; uint8_t chan[35]; uint8_t pklen; uint8_t packet[48]; uint8_t lhlen;"
         " uint8_t last_hop[48]; uint8_t stealth[35]; };")
o.append("static const struct qrack QV_RACKS[] = {")
for a in v["acks_routed"]["valid"]:
    d, ch, pk, lh = (bytes.fromhex(a[k]) for k in ("datagram", "channel_payload", "packet", "last_hop_packet"))
    o.append(f"\t{{{a['n']}, {a['k']}, {a['hash_size']}, {len(a['path'])}, {arr(''.join(a['path']), 6)}, {arr(a['pa'])}, "
             f"{len(d)}, {arr(d.hex(), 20)}, {len(ch)}, {arr(ch.hex(), 35)}, {len(pk)}, {arr(pk.hex(), 48)}, {len(lh)}, "
             f"{arr(lh.hex(), 48)}, {arr(a['stealth'])}}},")
o.append("};")
# retry
o.append("struct qretry { uint32_t n; uint8_t pc[29]; uint8_t pt[17]; uint8_t p4c[35]; uint8_t p6c[35]; };")
o.append("static const struct qretry QV_RETRY[] = {" + ", ".join(
    f"{{{r['n']}, {arr(r['pc'])}, {arr(r['pt'])}, {arr(r['payload_ff4c'])}, {arr(r['payload_ff6c'])}}}" for r in v["retry"]) + "};")
# slots
s = v["slots"]
o.append("struct qslotkey { uint32_t n_a; uint8_t ks[32]; uint32_t base_s; uint32_t off[6]; uint32_t off900[4]; uint32_t send_at[3]; };")
o.append("static const struct qslotkey QV_SLOT_KEYS[] = {" + ", ".join(
    f"{{{k['n_a']}, {arr(k['ks'])}, {k['base_s']}, {{{', '.join(map(str, k['offsets']))}}}, "
    f"{{{', '.join(map(str, k['offsets_900']))}}}, {{{', '.join(map(str, k['send_at']))}}}}}" for k in s["keys"]) + "};")
o.append("struct qslotcmd { uint32_t n_a; uint16_t k; uint8_t tag[4]; uint8_t pt[17]; uint8_t pc[29]; uint8_t pay[35]; uint8_t pay_retry[35]; };")
o.append("static const struct qslotcmd QV_SLOT_CMDS[] = {" + ", ".join(
    f"{{{c['n_a']}, {c['k']}, {arr(c['tag'])}, {arr(c['pt'])}, {arr(c['pc'])}, {arr(c['payload'])}, {arr(c['payload_retry'])}}}"
    for c in s["commands"]) + "};")
o.append("static const int32_t QV_WINDOWS[][6] = {" + ", ".join(
    f"{{{w['offset_s']}, {w['window_s']}, {w['early_s']}, {w['guard_ms']}, {w['open_ms']}, {w['close_ms']}}}"
    for w in s["windows"]) + "};")
o.append("struct qslotack { uint32_t n_a, n; uint16_t k; uint8_t pa[13]; uint8_t tag[4]; };")
o.append("static const struct qslotack QV_SLOT_ACKS[] = {" + ", ".join(
    f"{{{a['n_a']}, {a['n']}, {a['k']}, {arr(a['pa'])}, {arr(a['tag'])}}}" for a in s["acks_at_slot"]) + "};")
# tag schedule: events kind 0 flood, 1 ack, 2 prev_slot, 3 reboot, 4 sync
o.append("struct qsched { uint8_t scen; uint8_t kind; uint32_t n; int64_t t; uint8_t has_first; int64_t t_first;"
         " uint8_t sync; uint8_t a_valid; uint32_t a_n; int64_t a_t0; uint8_t a_early; uint8_t p_valid; uint32_t p_n;"
         " int64_t p_t0; uint8_t p_early; uint8_t left; };")
o.append("static const struct qsched QV_SCHED[] = {")
kinds = {"flood": 0, "ack": 1, "prev_slot": 2, "reboot": 3, "sync": 4}
for i, sc in enumerate(v["tag_schedule"]):
    for st in sc["steps"]:
        ev = st["event"]
        k = kinds[ev[0]]
        n = ev[1] if len(ev) > 1 else 0
        t = ev[2] if len(ev) > 2 else 0
        hf = 1 if len(ev) > 3 else 0
        tf = ev[3] if len(ev) > 3 else 0
        a, p = st.get("anchor"), st.get("prev")
        o.append(f"\t{{{i}, {k}, {n}, {t}, {hf}, {tf}, {int(st.get('sync', False))}, {int(a is not None)}, "
                 f"{a[0] if a else 0}, {a[1] if a else 0}, {a[2] if a else 0}, {int(p is not None)}, {p[0] if p else 0}, "
                 f"{p[1] if p else 0}, {p[2] if p else 0}, {st.get('prev_slots_left', 0)}}},")
o.append("};")
# areas
ar = v["areas"]
o.append("struct qrow { double lat, lon, r_km; const char *scope; const char *net; };")
o.append("static const struct qrow QV_ROWS[] = {" + ", ".join(
    f"{{{r[0]}, {r[1]}, {r[2]}, \"{r[3]}\", \"{r[4]}\"}}" for r in ar["rows"]) + "};")
o.append("struct qarea { const char *name; uint8_t has_fix; double lat, lon; const char *net; uint8_t border;"
         " const char *country; const char *area; uint8_t nlev; const char *lev[3]; };")
o.append("static const struct qarea QV_AREAS[] = {")
for c in ar["cases"]:
    lv = c["levels"]
    o.append(f"\t{{\"{c['name']}\", {int(c['lat'] is not None)}, {c['lat'] or 0}, {c['lon'] or 0}, \"{c['home_network']}\", "
             f"{int(c['same_radio_border'])}, {cs(ar['country_scope'][c['home_network']])}, {cs(c['area'])}, {len(lv)}, "
             f"{{{', '.join(cs(x) for x in lv + [None] * (3 - len(lv)))}}}}},")
o.append("};")
# ladder: kind 0 flood, 1 reset, 2 ack
o.append("struct qlad { uint8_t kind; uint8_t evidence, important; uint32_t now; int8_t wide; uint8_t lvl; uint8_t widened; uint32_t widened_at; };")
o.append("static const struct qlad QV_LADDER[] = {")
for st in ar["ladder"]:
    ev = st["event"]
    if ev[0] == "flood":
        o.append(f"\t{{0, {int(ev[1])}, {int(ev[2])}, {ev[3]}, {-1 if st['wide_lvl'] is None else st['wide_lvl']}, {st['lvl']}, "
                 f"{int(st['widened_at'] is not None)}, {st['widened_at'] or 0}}},")
    else:
        o.append(f"\t{{{1 if ev[0] == 'reset' else 2}, 0, 0, {ev[1]}, -1, {st['lvl']}, {int(st['widened_at'] is not None)}, "
                 f"{st['widened_at'] or 0}}},")
o.append("};")
o.append(f"static const uint8_t QV_LADDER_LEVELS = {ar['ladder_levels']};")
o.append("struct qtc { const char *scope; uint8_t key[16]; uint8_t type; uint8_t len; uint8_t payload[64]; uint16_t code; };")
o.append("static const struct qtc QV_TRANSPORT[] = {" + ", ".join(
    f"{{\"{t['scope']}\", {arr(t['key'])}, {t['payload_type']}, {len(bytes.fromhex(t['payload']))}, {arr(t['payload'], 64)}, {t['code']}}}"
    for t in v["transport"]) + "};")
o.append("static const uint32_t QV_HOLD[][3] = {" + ", ".join(f"{{{h}, {p}, {s or 0}}}" for h, p, s in v["hold"]) + "};")
(here / "qm_vectors.h").write_text("\n".join(o) + "\n")
